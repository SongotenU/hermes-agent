#!/usr/bin/env python3
"""Generate the capability catalog (DSH gen-doc-graphs discipline, Hermes edition).

Renders ONE table of every model-facing surface — slash commands and model tools —
with its defining module and exposure path, so a new command/tool that forgets its
docs shows up as a diff. Committed output:
``website/docs/developer-guide/capability-catalog.md``.

Run:  scripts/run-in-hermes-env python3 scripts/gen_capability_catalog.py
CI:   tests/hermes_cli/test_capability_catalog_current.py fails when the committed
      file drifts from a fresh render (same contract as gateway-command-parity).
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "website" / "docs" / "developer-guide" / "capability-catalog.md"

HEADER = """# Capability catalog

<!-- AUTO-GENERATED by scripts/gen_capability_catalog.py — do not edit by hand. -->

Every model-facing surface in one table: slash commands (from `COMMAND_REGISTRY`)
and model tools (from the tool registry after `discover_builtin_tools()`). Diff
this file in review — a new surface that lands without its row is a docs bug.

"""


def _commands() -> list[tuple[str, ...]]:
    sys.path.insert(0, str(ROOT))
    from hermes_cli.commands import COMMAND_REGISTRY

    rows = []
    for cmd in COMMAND_REGISTRY:
        surface = "/" + cmd.name
        scope = []
        if getattr(cmd, "cli_only", False):
            scope.append("cli-only")
        if getattr(cmd, "gateway_only", False):
            scope.append("gateway-only")
        if getattr(cmd, "gateway_config_gate", None):
            scope.append(f"gate:{cmd.gateway_config_gate}")
        rows.append((
            "command", surface, cmd.category, cmd.description.replace("|", "\\|"),
            ", ".join(scope) or "all surfaces",
        ))
    return sorted(rows, key=lambda r: r[1])


def _tools() -> list[tuple[str, ...]]:
    sys.path.insert(0, str(ROOT))
    from model_tools import discover_builtin_tools
    from tools.registry import registry

    discover_builtin_tools()
    rows = []
    for entry in sorted(registry.get_builtin_entries(), key=lambda e: e.name):
        flags = []
        if entry.is_read_only:
            flags.append("read-only")
        if getattr(entry, "is_destructive", False):
            flags.append("destructive")
        if entry.requires_env:
            flags.append("needs:" + ",".join(entry.requires_env))
        rows.append(("tool", entry.name, entry.toolset, ", ".join(flags) or "-", ""))
    return rows


def _table(rows: list[tuple[str, ...]], columns: tuple[str, ...]) -> str:
    out = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


def render() -> str:
    cmds = _commands()
    tools = _tools()
    body = "## Slash commands\n\n" + _table(
        cmds, ("kind", "surface", "category", "description", "scope"),
    )
    body += "\n## Model tools\n\n" + _table(
        tools, ("kind", "name", "toolset", "flags", "notes"),
    )
    body += f"\nTotals: {len(cmds)} commands, {len(tools)} tools.\n"
    return HEADER + body


def main() -> int:
    text = render()
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
